import { expect, test } from "@playwright/test";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";

for (const width of [390,768,1440]) {
  test(`owner package: isolated fictional network and layout at ${width}px`, async ({page},info)=>{
    test.skip(info.project.name !== "desktop-chromium", "explicit viewports run once");
    test.setTimeout(90000);
    await page.setViewportSize({width,height:width===390?844:width===768?1024:1100});
    const directory=resolve(process.env.OWNER_EVIDENCE_DIR||"docs/final-owner-review/after");mkdirSync(directory,{recursive:true});
    const errors=[];const apiWrites=[];const memberReads=[];
    page.on("pageerror",e=>errors.push(e.message));
    page.on("request",r=>{if(new URL(r.url()).pathname.startsWith("/api/")){if(!["GET","HEAD"].includes(r.method()))apiWrites.push(r.url());else memberReads.push(new URL(r.url()).pathname);}});
    const shot=async(name)=>{await page.screenshot({path:resolve(directory,`${name}-${width}.png`),fullPage:!["member-profile","member-gallery","gallery-post"].includes(name)});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);};
    await page.goto("/?demo=1");
    await expect(page.locator("#demo-banner")).toContainText("สมมติ");
    await expect(page.locator("#people-grid .person-card")).toHaveCount(16);
    await expect.poll(()=>page.locator("#people-grid img").evaluateAll(images=>images.filter(i=>i.complete&&i.naturalWidth>0).length)).toBe(16);
    await page.locator('[data-discovery-page="2"]').click();
    await expect(page.locator("#people-grid .person-card")).toHaveCount(4);
    await page.locator('[data-discovery-page="1"]').click();
    await shot("discovery");
    await page.locator('#primary-nav [data-tab="friends"]').click();
    await expect(page.locator("#friends-grid .person-card")).toHaveCount(10);
    await expect(page.locator("#requests-grid .person-card")).toHaveCount(5);
    const overlap=await page.locator("#friends-tab").evaluate(tab=>{const subtitle=tab.querySelector(".subtitle").getBoundingClientRect();const heading=tab.querySelector("h2").getBoundingClientRect();return subtitle.bottom>heading.top;});
    expect(overlap).toBe(false);await shot("friends");
    await page.locator('#primary-nav [data-tab="chat"]').click();
    await expect(page.locator(".conversation-list .conversation")).toHaveCount(10);
    await shot("inbox");
    await page.locator(".conversation-list .conversation").first().click();
    await expect(page.locator("#thread .message")).toHaveCount(12);
    const composer=await page.locator(".composer").boundingBox();
    const navigation=await page.locator(".sidebar").boundingBox();
    expect(composer.y+composer.height).toBeLessThanOrEqual(navigation.y-8);
    await shot("chat");
    await page.locator('#thread input[name="body"]').fill("ข้อความทดสอบสมมติในเบราว์เซอร์เท่านั้น");
    await page.locator(".composer").getByRole("button",{name:"ส่ง",exact:true}).click();
    await expect(page.locator("#thread .message")).toHaveCount(13);
    await page.locator('#primary-nav [data-tab="near"]').click();
    await page.locator('#people-grid [data-person="demo-02"]').click();
    await page.locator('.full-profile-info [data-action="report"]').click();
    await page.locator('#report-form textarea').fill("รายงานสมมติสำหรับทดสอบเฉพาะในเบราว์เซอร์");
    await page.locator('#report-form button').click();
    await expect(page.locator('#toast')).toContainText("บันทึกรายงานตัวอย่างในเบราว์เซอร์แล้ว");
    await page.locator('#people-grid [data-person="demo-02"]').click();
    // NEAR only exposes proximity ratings within 100m. This fixture is 500m
    // away; do not fabricate eligibility or force open an unavailable action.
    await expect(page.locator('.full-profile-actions [data-action=rate]')).toHaveCount(0);
    await page.keyboard.press('Escape');
    await page.locator('#primary-nav [data-tab="reviews"]').click();
    await expect(page.locator("#reviews-list .review")).toHaveCount(15);await shot("reviews");
    await page.locator('#primary-nav [data-tab="profile"]').click();
    await expect(page.locator("#my-gallery img")).toHaveCount(2);await shot("settings-gallery-notifications");
    await page.locator('#primary-nav [data-tab="near"]').click();
    await page.locator('#people-grid [data-person="demo-02"]').click();
    await expect(page.locator(".full-profile:not(.gallery-page)")).toBeVisible();await shot("member-profile");
    await expect(page.locator(".full-profile-info .fixture-label")).toContainText("สมมติ");
    const back=await page.locator('.profile-back').boundingBox();
    const brand=await page.locator('.profile-page-brand').boundingBox();
    const galleryControl=await page.locator('.profile-gallery-top').boundingBox();
    expect(back.x+back.width).toBeLessThanOrEqual(brand.x);
    expect(brand.x+brand.width).toBeLessThanOrEqual(galleryControl.x);
    await page.locator(".profile-gallery-top").click();
    await expect(page.locator('.gallery-summary [data-action="chat"]')).toBeVisible();
    await expect(page.locator('.gallery-page [data-action="report"]')).toBeVisible();
    await expect(page.locator(".gallery-page")).toBeVisible();await shot("member-gallery");
    await page.locator("#dialog-gallery button").first().click();
    await expect(page.locator(".gallery-post-page")).toBeVisible();
    await expect(page.locator(".post-owner .fixture-label")).toContainText("สมมติ");
    await page.locator('.post-like').click();
    await expect(page.locator('.post-like')).toHaveAttribute('aria-pressed','true');
    await page.locator("#gallery-comment input[name=comment]").fill("ภาพตัวอย่างน่ารักดี");
    await page.locator("#gallery-comment button").click();
    await expect(page.locator(".post-comments")).toContainText("ภาพตัวอย่างน่ารักดี");await shot("gallery-post");
    await page.locator('#profile-dialog [data-gallery-return]').click();
    await page.locator('#profile-dialog [data-close-profile]').click();
    await page.reload();await expect(page.locator("#demo-banner")).toBeVisible();
    await page.locator('#primary-nav [data-tab="chat"]').click();await page.locator(".conversation-list .conversation").first().click();
    await expect(page.locator("#thread .message")).toHaveCount(13);
    expect(apiWrites).toEqual([]);
    expect(memberReads.every(p=>["/api/social/config","/api/auth/me"].includes(p))).toBe(true);
    expect(errors).toEqual([]);
    await page.goto("/app/moderation.html");
    await expect(page.locator("#moderation-results .moderation-card")).toHaveCount(0);
    await shot("anonymous-admin-denied");
  });
}
